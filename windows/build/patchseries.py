"""The windows/patches series: reading, linting and applying (stdlib only, needs `git` on PATH).

The series is a list of `git format-patch` files made on top of the *unmodified* bunkerweb/src tree (the layout of the
files is `a/<path below src>`). windows/patches/.patches lists them in the order they are applied. Nothing here touches
bunkerweb/ itself: apply_series() works on the copy that apply-windows-port.py prepared.

Every patch must say why it exists and what its upstream status is (see windows/patches/README.md, generated by
patchtool.py), the same rule the Electron project applies to its Chromium/Node patches.
"""

import os
import re
import subprocess
from pathlib import Path

SERIES_FILE = ".patches"
REQUIRED_FIELDS = ("Upstream", "Check")
_FIELD_RE = re.compile(r"^(Upstream|Check):[ \t]*(.*\S)[ \t]*$", re.M)


def read_series(patches_dir):
    """Ordered patch file names from .patches (comments and blank lines ignored)."""
    path = Path(patches_dir) / SERIES_FILE
    if not path.is_file():
        return []
    names = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            names.append(line)
    return names


def parse_patch(path):
    """Subject, body and the Upstream/Check fields of a git format-patch file."""
    text = Path(path).read_text(encoding="utf-8")
    head, _, rest = text.partition("\n\n")
    subject = ""
    lines = head.splitlines()
    for i, line in enumerate(lines):
        if line.startswith("Subject:"):
            subject = line[len("Subject:"):].strip()
            for cont in lines[i + 1:]:
                if cont[:1] in (" ", "\t"):
                    subject += " " + cont.strip()
                else:
                    break
            break
    subject = re.sub(r"^\[PATCH[^\]]*\]\s*", "", subject)
    body = rest.split("\n---\n", 1)[0].strip()
    fields = {m.group(1): m.group(2) for m in _FIELD_RE.finditer(body)}
    return {"subject": subject, "body": body, "fields": fields}


def lint(patches_dir):
    """Problems with the series as a whole (missing/unlisted files, missing reason/upstream/check)."""
    patches_dir = Path(patches_dir)
    problems = []
    series = read_series(patches_dir)
    if len(series) != len(set(series)):
        problems.append(".patches lists a patch twice")
    listed = set(series)
    for name in series:
        path = patches_dir / name
        if not path.is_file():
            problems.append(f"{name}: listed in {SERIES_FILE} but the file does not exist")
            continue
        info = parse_patch(path)
        if not info["subject"]:
            problems.append(f"{name}: no Subject header (not a git format-patch file?)")
        reason = _FIELD_RE.sub("", info["body"]).strip()
        if len(reason) < 20:
            problems.append(f"{name}: the commit message must explain why the patch exists")
        for field in REQUIRED_FIELDS:
            if field not in info["fields"]:
                problems.append(f"{name}: commit message lacks a '{field}: ...' line")
    for path in sorted(patches_dir.glob("*.patch")):
        if path.name not in listed:
            problems.append(f"{path.name}: not listed in {SERIES_FILE}")
    return problems


def _git(args, cwd, src=None):
    env = dict(os.environ)
    if src is not None:
        # `git apply` inside a subdirectory of another repository (build/src lives in this repo) would interpret the
        # patch paths relative to that repository's top level: hide it, so the paths are relative to the copy
        env["GIT_CEILING_DIRECTORIES"] = str(Path(src).resolve().parent)
    return subprocess.run(["git", *args], cwd=cwd, env=env, capture_output=True, text=True, encoding="utf-8")


def apply_series(src, patches_dir):
    """Apply every patch of the series to the copy `src`. Returns a list of error strings (empty = success)."""
    src = Path(src).resolve()
    patches_dir = Path(patches_dir).resolve()
    errors = [f"patch series: {problem}" for problem in lint(patches_dir)]
    if errors:
        return errors
    for name in read_series(patches_dir):
        patch = patches_dir / name
        base = ["apply", "--whitespace=nowarn"]
        check = _git([*base, "--check", str(patch)], src, src)
        if check.returncode != 0:
            detail = " | ".join(line.strip() for line in check.stderr.splitlines() if line.strip())
            errors.append(f"patch {name} does not apply to this upstream version: {detail}")
            continue
        applied = _git([*base, str(patch)], src, src)
        if applied.returncode != 0:
            errors.append(f"patch {name}: git apply failed: {applied.stderr.strip()}")
            continue
        print(f"  patch   {name}: {parse_patch(patch)['subject']}")
    return errors
