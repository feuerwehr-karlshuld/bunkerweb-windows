#!/usr/bin/env python3
"""Maintain windows/patches (the patch series applied on top of bunkerweb/src) the way git is meant to be used.

The series is a stack of commits on top of an unmodified upstream tree. To change it or to move it to a new upstream
release you work in a scratch git repository (default: build/patchwork) with normal git tooling and export the result.
Nothing is ever written to the bunkerweb/ submodule (it is only read with `git archive`).

  patchtool.py import [--rev REV] [--repo DIR] [--workdir DIR] [--force]
      Builds the scratch repo: the upstream tree the series was made against (windows/patches/BASE) plus the series applied
      with `git am`. With --rev (a tag/commit of the bunkerweb submodule, default: what the submodule has checked out) the
      series is then rebased onto that upstream version with `git rebase --onto`, i.e. with git's 3-way merge. On a
      conflict git stops in the scratch repo: resolve it, `git add`, `git rebase --continue`, then run `export`.
  patchtool.py export [--workdir DIR]
      Writes the commits of the scratch repo (everything above the upstream tree) to windows/patches/*.patch, rewrites
      .patches and BASE. Re-exporting an unchanged series is byte-for-byte stable.
  patchtool.py lint
      Checks the series: files listed/present, every patch explains why it exists and has Upstream: and Check: lines.

To add a patch: `import`, edit the files in the scratch repo, `git commit` (subject = what, body = why, plus the two lines
`Upstream: <link or "none, Windows specific">` and `Check: <how to see whether the patch is still needed>`), `export`.
To edit a patch: `git commit --fixup <sha>`, `git rebase --autosquash -i <sha>^`, `export`.

Run it on Linux/macOS/WSL (the upstream tree contains symlinks), `git` and Python >= 3.12 required.
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import patchseries  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
PATCHES = ROOT / "windows" / "patches"
SUBMODULE = ROOT / "bunkerweb"
DEFAULT_WORKDIR = ROOT / "build" / "patchwork"
UPSTREAM_REF = "refs/patches/upstream-head"
AUTHOR = ("BunkerWeb Windows port", "bunkerweb-windows@users.noreply.invalid")
HEADER = (
    "# Patch series of the BunkerWeb Windows port, applied in this order to a copy of bunkerweb/src.\n"
    "# Generated by windows/build/patchtool.py export. Do not edit by hand.\n"
)


def die(message):
    print(f"patchtool: {message}", file=sys.stderr)
    sys.exit(1)


def git(args, cwd, check=True, capture=True, env=None):
    full_env = dict(os.environ)
    full_env.update(env or {})
    result = subprocess.run(["git", *args], cwd=cwd, env=full_env, text=True, encoding="utf-8", capture_output=capture)
    if check and result.returncode != 0:
        die(f"git {' '.join(args)} failed in {cwd}:\n{(result.stderr or '').strip()}")
    return result


def resolve_commit(repo, rev):
    result = git(["rev-parse", "--verify", "--quiet", f"{rev}^{{commit}}"], repo, check=False)
    if result.returncode != 0:
        die(f"cannot resolve {rev!r} in {repo} (fetch the tag first: git -C bunkerweb fetch --tags)")
    return result.stdout.strip()


def describe(repo, sha):
    result = git(["describe", "--tags", "--always", sha], repo, check=False)
    return result.stdout.strip() if result.returncode == 0 else sha[:12]


def read_base():
    path = PATCHES / "BASE"
    if not path.is_file():
        return None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            return line.split()[0]
    return None


def extract_src(repo, sha, dest):
    """Unpack <sha>:src of the upstream repository into dest.

    Read-only use of the submodule: a temporary index file is filled with the tree and checked out into dest, neither the
    index nor the working tree of the submodule is touched. (`git archive` is not used: it honours upstream's
    export-ignore/export-subst attributes and would not give the tree that is built.)
    """
    index = Path(tempfile.mkdtemp(prefix="patchtool-index-")) / "index"
    try:
        env = {"GIT_INDEX_FILE": str(index)}
        git(["read-tree", f"{sha}:src"], repo, env=env)
        git(["checkout-index", "--all", "--force", f"--prefix={Path(dest).resolve().as_posix()}/"], repo, env=env)
    finally:
        shutil.rmtree(index.parent, ignore_errors=True)


def clear_worktree(workdir):
    for entry in workdir.iterdir():
        if entry.name == ".git":
            continue
        shutil.rmtree(entry) if entry.is_dir() and not entry.is_symlink() else entry.unlink()


def commit_all(workdir, message):
    git(["add", "-A", "--force"], workdir)
    env = {
        "GIT_AUTHOR_NAME": AUTHOR[0], "GIT_AUTHOR_EMAIL": AUTHOR[1], "GIT_AUTHOR_DATE": "2000-01-01T00:00:00+0000",
        "GIT_COMMITTER_NAME": AUTHOR[0], "GIT_COMMITTER_EMAIL": AUTHOR[1], "GIT_COMMITTER_DATE": "2000-01-01T00:00:00+0000",
    }
    git(["commit", "-q", "--allow-empty", "--no-verify", "-m", message], workdir, env=env)
    return git(["rev-parse", "HEAD"], workdir).stdout.strip()


def cmd_import(args):
    repo = Path(args.repo).resolve()
    workdir = Path(args.workdir).resolve()
    if workdir.exists():
        if not args.force:
            die(f"{workdir} exists (use --force to throw it away)")
        shutil.rmtree(workdir)
    series = patchseries.read_series(PATCHES)
    new_sha = resolve_commit(repo, args.rev or "HEAD")
    base_sha = read_base() if series else new_sha
    if base_sha is None:
        die("windows/patches/BASE is missing")
    base_sha = resolve_commit(repo, base_sha)

    workdir.mkdir(parents=True)
    git(["init", "-q", "-b", "patches"], workdir)
    for key, value in (("user.name", AUTHOR[0]), ("user.email", AUTHOR[1]), ("core.autocrlf", "false"),
                       ("core.safecrlf", "false"), ("commit.gpgsign", "false"), ("core.longpaths", "true")):
        git(["config", key, value], workdir)

    print(f"upstream tree {describe(repo, base_sha)} ({base_sha[:12]}) ...")
    extract_src(repo, base_sha, workdir)
    base_commit = commit_all(workdir, f"upstream {describe(repo, base_sha)}")
    git(["update-ref", UPSTREAM_REF, base_commit], workdir)
    git(["config", "patchtool.upstream", base_sha], workdir)

    if series:
        print(f"applying {len(series)} patches ...")
        patches = [str(PATCHES / name) for name in series]
        result = git(["am", "--no-3way", "--quiet", *patches], workdir, check=False)
        if result.returncode != 0:
            die("the series does not apply to the tree recorded in BASE:\n" + (result.stderr or result.stdout))

    if new_sha != base_sha:
        print(f"moving the series to upstream {describe(repo, new_sha)} ({new_sha[:12]}) ...")
        git(["checkout", "-q", "--orphan", "upstream-new"], workdir)
        clear_worktree(workdir)
        extract_src(repo, new_sha, workdir)
        new_commit = commit_all(workdir, f"upstream {describe(repo, new_sha)}")
        git(["checkout", "-q", "patches"], workdir)
        git(["update-ref", UPSTREAM_REF, new_commit], workdir)
        git(["config", "patchtool.upstream", new_sha], workdir)
        rebase = git(["rebase", "--onto", new_commit, base_commit, "patches"], workdir, check=False)
        if rebase.returncode != 0:
            print(rebase.stdout + rebase.stderr)
            print(
                f"\nConflicts while moving the series. Resolve them in {workdir}:\n"
                "  git status; edit the files; git add <files>; git rebase --continue\n"
                f"then run: {Path(sys.argv[0]).name} export"
            )
            sys.exit(2)
    print(f"\nScratch repository ready: {workdir}\nEdit and commit there, then run: {Path(sys.argv[0]).name} export")


def slug(subject):
    return re.sub(r"[^a-z0-9]+", "-", subject.lower()).strip("-")[:64] or "patch"


def cmd_export(args):
    workdir = Path(args.workdir).resolve()
    if not (workdir / ".git").exists():
        die(f"{workdir} is not a scratch repository (run import first)")
    if git(["status", "--porcelain", "--untracked-files=no"], workdir).stdout.strip():
        die("uncommitted changes in the scratch repository: commit them first (git export only sees commits)")
    if (workdir / ".git" / "rebase-merge").exists() or (workdir / ".git" / "rebase-apply").exists():
        die("a rebase is still in progress in the scratch repository")
    upstream = git(["rev-parse", "--verify", UPSTREAM_REF], workdir).stdout.strip()
    shas = git(["rev-list", "--reverse", "--no-merges", f"{upstream}..HEAD"], workdir).stdout.split()
    upstream_sha = git(["config", "patchtool.upstream"], workdir).stdout.strip()

    PATCHES.mkdir(parents=True, exist_ok=True)
    names, seen = [], set()
    for sha in shas:
        patch = git(["format-patch", "-1", "--stdout", "--zero-commit", "--no-signature", "--no-stat", "--no-numbered", sha], workdir).stdout
        subject = re.search(r"^Subject: (?:\[PATCH[^\]]*\] )?(.*)$", patch, re.M).group(1)
        name = slug(subject) + ".patch"
        if name in seen:
            die(f"two patches have the subject {subject!r}")
        seen.add(name)
        names.append(name)
        (PATCHES / name).write_text(patch, encoding="utf-8", newline="\n")
    for stale in PATCHES.glob("*.patch"):
        if stale.name not in seen:
            stale.unlink()
            print(f"removed {stale.name}")
    (PATCHES / patchseries.SERIES_FILE).write_text(HEADER + "".join(f"{n}\n" for n in names), encoding="utf-8", newline="\n")
    (PATCHES / "BASE").write_text(
        "# bunkerweb submodule commit the series was made against (generated by patchtool.py export)\n"
        f"{upstream_sha} {describe(SUBMODULE, upstream_sha)}\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"exported {len(names)} patches to {PATCHES}")
    problems = patchseries.lint(PATCHES)
    for problem in problems:
        print(f"  lint: {problem}")
    sys.exit(1 if problems else 0)


def cmd_lint(_args):
    problems = patchseries.lint(PATCHES)
    for problem in problems:
        print(f"lint: {problem}")
    if not problems:
        print(f"{len(patchseries.read_series(PATCHES))} patches, no problems")
    sys.exit(1 if problems else 0)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    p_import = sub.add_parser("import")
    p_import.add_argument("--rev", help="bunkerweb commit/tag to move the series to (default: the submodule's checkout)")
    p_import.add_argument("--repo", default=str(SUBMODULE), help="repository the upstream trees are read from")
    p_import.add_argument("--workdir", default=str(DEFAULT_WORKDIR))
    p_import.add_argument("--force", action="store_true")
    p_import.set_defaults(func=cmd_import)
    p_export = sub.add_parser("export")
    p_export.add_argument("--workdir", default=str(DEFAULT_WORKDIR))
    p_export.set_defaults(func=cmd_export)
    sub.add_parser("lint").set_defaults(func=cmd_lint)
    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
