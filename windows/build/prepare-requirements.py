#!/usr/bin/env python3
"""Merge BunkerWeb's pip-compile'd requirement files into one hash-pinned file for Windows.

The Linux packages run `pip install --require-hashes -r a.txt -r b.txt ...` with every
component's requirements at once. pip refuses duplicate hash-pinned requirements coming from
different files when their hash sets differ, so we merge them here: same name + same specifier
-> union of hashes; a different specifier for the same name is an error (upstream inconsistency).

Usage: python prepare-requirements.py <bunkerweb/src> <output.txt> [--drop name ...]
"""

import re
import sys
from pathlib import Path

COMPONENT_FILES = (
    "scheduler/requirements.txt",
    "ui/requirements.txt",
    "api/requirements.txt",
    "common/gen/requirements.txt",
    "common/db/requirements.txt",
)

# uvloop has no Windows support (uvicorn falls back to asyncio, see bwsvc.py)
DEFAULT_DROP = {"uvloop"}


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def parse(path: Path) -> dict:
    blocks = {}
    current = None
    for raw in path.read_text(encoding="utf-8").splitlines():
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue
        content = stripped.rstrip("\\").strip()
        if not raw[0].isspace():
            name = normalize(re.split(r"[\s=<>!~;@\[]", content, maxsplit=1)[0])
            current = {"spec": re.sub(r"\s+", " ", content), "hashes": set(), "source": str(path)}
            blocks[name] = current
        elif content.startswith("--hash=") and current is not None:
            current["hashes"].add(content)
        elif content.startswith("--"):
            raise SystemExit(f"{path}: unsupported option line: {content}")
    return blocks


def main() -> int:
    if len(sys.argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    src = Path(sys.argv[1])
    output = Path(sys.argv[2])
    drop = set(DEFAULT_DROP)
    if "--drop" in sys.argv:
        drop |= {normalize(name) for name in sys.argv[sys.argv.index("--drop") + 1 :]}

    merged = {}
    errors = []
    for rel in COMPONENT_FILES:
        for name, block in parse(src / rel).items():
            if name in drop:
                continue
            if name not in merged:
                merged[name] = block
                continue
            if merged[name]["spec"] != block["spec"]:
                errors.append(f"{name}: {merged[name]['spec']!r} ({merged[name]['source']}) != {block['spec']!r} ({block['source']})")
                continue
            merged[name]["hashes"] |= block["hashes"]

    if errors:
        print("Conflicting requirement pins:", file=sys.stderr)
        for error in errors:
            print(f"  - {error}", file=sys.stderr)
        return 1

    missing = [name for name, block in merged.items() if not block["hashes"]]
    if missing:
        print(f"Requirements without hashes: {', '.join(missing)}", file=sys.stderr)
        return 1

    lines = ["# Generated by windows/build/prepare-requirements.py - do not edit"]
    for name in sorted(merged):
        block = merged[name]
        hashes = sorted(block["hashes"])
        lines.append(f"{block['spec']} \\")
        lines += [f"    {h} \\" for h in hashes[:-1]]
        lines.append(f"    {hashes[-1]}")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(merged)} requirements to {output} (dropped: {', '.join(sorted(drop))})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
